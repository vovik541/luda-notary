// Post-build for the static site (dist/site/browser), run after `ng build`.
// Usage: node scripts/postbuild.mjs [production]   (default: preview)
//
// 1. Per-locale 404 pages: {locale}/404/index.html → {locale}/404.html, served by Workers with a real 404 status.
// 2. _redirects: one-hop 301s from every legacy URL of www.mobilenotary-sacramento.com (plan §3).
// 3. _headers: security and caching headers for static assets (the API Worker sets its own).
// 4. robots.txt and sitemap.xml by environment; the sitemap is built from the pages' own canonical/hreflang tags,
//    so it can only list pages that really exist, are indexable and are self-canonical.
import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CITIES } from '../src/app/content/site.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'dist', 'site', 'browser');
const env = process.argv[2] === 'production' ? 'production' : 'preview';
const angular = JSON.parse(readFileSync(join(root, 'angular.json'), 'utf8'));
const defines = angular.projects.site.architect.build.configurations[env].define;
const SITE_URL = JSON.parse(defines.SITE_URL);
const fail = (m) => { console.error(`postbuild failed: ${m}`); process.exit(1); };
if (!existsSync(join(out, 'index.html'))) fail('run ng build first');

// 1. 404 pages
for (const prefix of ['', 'uk', 'ru']) {
  const from = join(out, prefix, '404', 'index.html');
  if (!existsSync(from)) fail(`missing ${relative(out, from)}`);
  renameSync(from, join(out, prefix, '404.html'));
  rmSync(join(out, prefix, '404'), { recursive: true, force: true });
}
rmSync(join(out, 'index.csr.html'), { force: true }); // no SPA fallback: unknown paths must 404

// 2. Legacy redirects (single hop, final targets only)
const cityTarget = (slug) => (CITIES.find((c) => c.slug === slug)?.indexed ? `/mobile-notary/${slug}/` : '/service-area/');
const legacy = [
  ['/index.html', '/'],
  ['/about.html', '/'],
  ['/services.html', '/notary/'],
  ['/services/mobile-notary.html', '/notary/'],
  ['/services/loan-signing.html', '/notary/'], // blocker B4: own page if loan signing stays
  ['/service-area.html', '/service-area/'],
  ['/contact.html', '/'],
  ['/privacy-policy.html', '/privacy/'],
  ['/terms-of-service.html', '/terms/'],
  ['/terms-of-use.html', '/terms/'],
  ...['antelope', 'arden-arcade', 'auburn', 'carmichael', 'citrus-heights', 'elk-grove', 'fair-oaks', 'folsom', 'lincoln', 'north-highlands', 'orangevale', 'rancho-cordova', 'rio-linda', 'rocklin', 'roseville', 'sacramento']
    .map((s) => [`/cities/${s}-mobile-notary.html`, cityTarget(s)]),
];
// Cities that do not qualify for their own page: their new URL redirects to the hub in every locale.
const retired = CITIES.filter((c) => !c.indexed).flatMap((c) => ['', '/uk', '/ru'].map((p) => [`${p}/mobile-notary/${c.slug}/`, `${p}/service-area/`]));
const redirects = [...legacy, ...retired];
writeFileSync(join(out, '_redirects'), `# Generated by scripts/postbuild.mjs: legacy www.mobilenotary-sacramento.com URLs and retired city pages.\n${redirects.map(([a, b]) => `${a} ${b} 301`).join('\n')}\n`);

// 3. Headers for static responses
const csp = [
  "default-src 'self'", "script-src 'self' 'unsafe-inline' https://challenges.cloudflare.com", "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:", "font-src 'self'", "connect-src 'self'", "frame-src https://challenges.cloudflare.com",
  "base-uri 'self'", "form-action 'self'", "frame-ancestors 'none'", "object-src 'none'",
].join('; ');
writeFileSync(join(out, '_headers'), `/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  Referrer-Policy: strict-origin-when-cross-origin
  X-Content-Type-Options: nosniff
  Permissions-Policy: camera=(), microphone=(), geolocation=(), interest-cohort=()
  Cache-Control: public, max-age=0, must-revalidate${env === 'preview' ? '\n  X-Robots-Tag: noindex, nofollow' : ''}
/*.js
  Cache-Control: public, max-age=31536000, immutable
/*.css
  Cache-Control: public, max-age=31536000, immutable
/fonts/*
  Cache-Control: public, max-age=31536000, immutable
/img/*
  Cache-Control: public, max-age=604800
/brand/*
  Cache-Control: public, max-age=604800
`);

// 4. robots.txt and sitemap.xml
const pages = [];
const walk = (d) => readdirSync(d).forEach((f) => { const p = join(d, f); statSync(p).isDirectory() ? walk(p) : f.endsWith('.html') && pages.push(p); });
walk(out);
const entries = [];
for (const file of pages) {
  const html = readFileSync(file, 'utf8');
  const rel = '/' + relative(out, file).replaceAll('\\', '/');
  const url = SITE_URL + rel.replace(/index\.html$/, '').replace(/\.html$/, '');
  const canonical = html.match(/<link rel="canonical" href="([^"]+)"/)?.[1];
  const robots = html.match(/<meta name="robots" content="([^"]+)"/)?.[1] ?? '';
  if (!canonical || canonical !== url || /noindex/.test(robots) || rel.endsWith('404.html')) continue;
  const alternates = [...html.matchAll(/<link rel="alternate" hreflang="([^"]+)" href="([^"]+)"/g)].map((m) => [m[1], m[2]]);
  entries.push({ url, alternates });
}
if (env === 'production') {
  writeFileSync(join(out, 'robots.txt'), `User-agent: *\nAllow: /\nDisallow: /api/\nDisallow: /request/\n\nSitemap: ${SITE_URL}/sitemap.xml\n`);
  const today = new Date().toISOString().slice(0, 10);
  writeFileSync(join(out, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${entries
    .sort((a, b) => a.url.localeCompare(b.url))
    .map((e) => `  <url>\n    <loc>${e.url}</loc>\n    <lastmod>${today}</lastmod>\n${e.alternates.map(([l, h]) => `    <xhtml:link rel="alternate" hreflang="${l}" href="${h}"/>`).join('\n')}\n  </url>`)
    .join('\n')}\n</urlset>\n`);
} else {
  writeFileSync(join(out, 'robots.txt'), 'User-agent: *\nDisallow: /\n');
  rmSync(join(out, 'sitemap.xml'), { force: true });
}

console.log(`postbuild (${env}): ${pages.length} HTML files · ${redirects.length} redirects · sitemap ${env === 'production' ? `${entries.length} URLs` : 'none (preview)'} · ${SITE_URL}`);
