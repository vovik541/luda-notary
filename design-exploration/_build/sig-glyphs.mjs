// Builds assets/js/sig-glyphs.js: single-stroke script paths for the A2 signature line.
// Source: EMS Allure (assets/fonts/EMSAllure.svg), SIL Open Font License; a single-line derivative of Allura.
// Glyph polylines are smoothed into cubic curves (Catmull-Rom) and flipped to SVG's y-down space.
// Units: 1000 per em, baseline at y = 0, words start at x = 0.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const src = readFileSync(new URL('assets/fonts/EMSAllure.svg', root), 'utf8');

const glyphs = {};
for (const m of src.matchAll(/<glyph ([^>]*)\/>/g)) {
  const a = Object.fromEntries([...m[1].matchAll(/([\w-]+)="([^"]*)"/g)].map((x) => [x[1], x[2]]));
  if (a.unicode) glyphs[a.unicode.replace('&amp;', '&')] = { adv: +(a['horiz-adv-x'] || 378), d: a.d || '' };
}

const strokes = (d) => {
  const out = []; let cur;
  for (const [, cmd, nums] of d.matchAll(/([MLC])([^MLC]*)/g)) {
    const v = nums.trim().split(/\s+/).map(Number);
    if (cmd === 'M') { cur = [[v[0], v[1]]]; out.push(cur); } else cur.push([v.at(-2), v.at(-1)]);
  }
  return out;
};

const r = (n) => Math.round(n);
const smooth = (pts) => {
  const p = pts.map(([x, y]) => [x, -y]);
  let s = `M${r(p[0][0])} ${r(p[0][1])}`;
  for (let i = 0; i < p.length - 1; i++) {
    const a = p[i - 1] || p[i], b = p[i], c = p[i + 1], e = p[i + 2] || c;
    s += ` C${r(b[0] + (c[0] - a[0]) / 6)} ${r(b[1] + (c[1] - a[1]) / 6)} ${r(c[0] - (e[0] - b[0]) / 6)} ${r(c[1] - (e[1] - b[1]) / 6)} ${r(c[0])} ${r(c[1])}`;
  }
  return s;
};

// track: extra advance after given characters (the Allure "L" otherwise swallows the "p" of the monogram)
const word = (text, track = {}) => {
  let x = 0; const parts = [];
  for (const ch of text) {
    const g = glyphs[ch] || { adv: 300, d: '' };
    for (const st of strokes(g.d)) parts.push(smooth(st.map(([px, py]) => [px + x, py])));
    x += g.adv + (track[ch] || 0);
  }
  return { d: parts.join(' '), w: r(x) };
};

const data = {
  Liudmyla: word('Liudmyla'),
  Petruk: word('Petruk'),
  Lp: word('Lp', { L: 330 }),
  Notary: word('Notary'),
  phone: word('+1 (916) 301-3829'),
};
writeFileSync(new URL('assets/js/sig-glyphs.js', root),
  `// Generated by _build/sig-glyphs.mjs. Script paths from EMS Allure (SIL Open Font License), derivative of Allura.\n` +
  `window.SIG_GLYPHS = ${JSON.stringify(data)};\n`);
console.log(Object.fromEntries(Object.entries(data).map(([k, v]) => [k, `${v.w}u, ${v.d.length}b`])));
